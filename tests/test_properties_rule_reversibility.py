"""
Property-based tests for transformation-rule reversibility (issue #8).

Two distinct kinds of "reversibility" are tested here, because DC+/DC− and
ERA/INS sit differently in Dau's calculus:

1. ``DC+ ↔ DC−`` is a true *semantic equivalence pair*: double cuts cancel,
   so inserting then erasing them (or vice versa) yields a graph identical
   to the original. We test the structural round-trip directly.

2. ``ERA + INS`` are one-directional sound rules with opposite polarity
   requirements (ERA needs a positive area, INS needs a negative one) — they
   are *not* a soundness-preserving inverse pair in the same area. Issue
   #8's literal phrasing isn't directly realizable. What is realizable, and
   genuinely useful, is checking ERA's *mutation bookkeeping*: the result
   of ERA must equal the original EGI minus exactly the closure of the
   erased selection (no over-erasure, no under-erasure, no positional drift).
   The ``ERA-restore`` test exercises this: it removes a closed subgraph,
   then re-adds the same elements at the same positions, and asserts
   structural identity with the original. A failure here would surface as
   either ERA erasing too much (e.g. a shared identity vertex that should
   have remained semi-free) or its closure missing transitively required
   elements.

Both tests follow the seed-by-applying-rules pattern recommended in #8:
the input EGI is generated by parsing a well-formed EGIF, and the seed
strategy guarantees that preconditions hold by construction.
"""

