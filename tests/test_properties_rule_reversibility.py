@st.composite
def _seed_egi(draw):
    """Parse a generated EGIF into an EGI. Skip empty or unparseable shapes."""
    text = draw(egif_sheet(max_atoms=3, max_cut_depth=1))
    try:
        egi = parse_egif(text)
    except Exception:
        assume(False)
        return None
    return egi


def _direct_area_contents(egi: RelationalGraphWithCuts, area_id: ElementID):
    """Direct contents of ``area_id`` (not recursive into nested cuts)."""
    return egi.area.get(area_id, frozenset())


def _is_positive_area(egi: RelationalGraphWithCuts, area_id: ElementID) -> bool:
    polarity, _ = egi.area_polarity(area_id)
    return polarity is AreaPolarity.POSITIVE


# --------------------------------------------------------------------------- #
# DC+ ↔ DC− structural round-trip                                             #
# --------------------------------------------------------------------------- #


@st.composite
def _dcplus_target(draw):
    """Generate ``(egi, target_area, selected_subgraph)`` for a DC+ application.

    DC+ has no polarity restriction. ``selected_subgraph`` may be empty (DC+
    encloses everything in the area in that case) or any subset of the area's
    *direct* contents.
    """
    egi = draw(_seed_egi())
    area_id = draw(st.sampled_from(list(egi.area.keys())))
    contents = list(_direct_area_contents(egi, area_id))
    if not contents:
        # DC+ on an empty area is degenerate; skip
        assume(False)
    selection = draw(st.sets(st.sampled_from(contents)))
    return egi, area_id, frozenset(selection)


class TestDoubleCutReversibility:
    """DC+ then DC− on the just-added outer cut reproduces the original EGI."""

    @settings(
        max_examples=120,
        deadline=None,
        suppress_health_check=[HealthCheck.too_slow, HealthCheck.filter_too_much],
    )
    @given(_dcplus_target())
    def test_dc_plus_minus_round_trip_is_structural_identity(self, params):
        egi, area_id, selection = params

        polarity, depth = egi.area_polarity(area_id)
        ctx_plus = TransformationContext(
            source_egi=egi,
            target_area=area_id,
            selected_subgraph=selection,
            area_polarity=polarity,
            nesting_depth=depth,
        )

        plus_result = DoubleCutInsertionRule().apply_transformation(ctx_plus)
        assert plus_result.success, f"DC+ failed: {plus_result.error_message}"
        g_plus = plus_result.result_egi
        outer_cut_id = ElementID(plus_result.changes_made["outer_cut"])

        # DC− on the outer cut should remove both added cuts.
        polarity2, depth2 = g_plus.area_polarity(area_id)
        ctx_minus = TransformationContext(
            source_egi=g_plus,
            target_area=area_id,
            selected_subgraph=frozenset([outer_cut_id]),
            area_polarity=polarity2,
            nesting_depth=depth2,
        )
        minus_result = DoubleCutErasureRule().apply_transformation(ctx_minus)
        assert minus_result.success, f"DC- failed: {minus_result.error_message}"
        g_final = minus_result.result_egi

        # Structural identity: every field of the EGI must equal the original.
        assert g_final.sheet == egi.sheet
        assert g_final.V == egi.V
        assert g_final.E == egi.E
        assert g_final.Cut == egi.Cut, (
            f"Cut mismatch: original={ {c.id for c in egi.Cut} } "
            f"final={ {c.id for c in g_final.Cut} }"
        )
        assert g_final.nu == egi.nu
        assert g_final.rel == egi.rel
        # ``area`` is a frozendict — compare as dicts.
        assert dict(g_final.area) == dict(egi.area), (
            f"area mismatch:\n  original={dict(egi.area)}\n  final={dict(g_final.area)}"
        )


# --------------------------------------------------------------------------- #
# ERA mutation reversibility                                                   #
# --------------------------------------------------------------------------- #


@st.composite
def _era_target(draw):
    """Generate ``(egi, positive_area, raw_selection)`` for an ERA application.

    Picks a positive area and draws a non-empty subset of its *direct*
    contents as the raw selection — ERA's precondition requires the
    selection itself (before closure expansion) to live in the target
    area's direct contents. The closure expansion that ERA performs
    internally may then pull in cut interiors and semi-free vertices from
    other areas; those are removed by ERA's mutation but are not part of
    the user-facing selection.

    The strategy filters to selections whose Beta-aware closure is in fact
    closed, so ERA's preconditions hold by construction.
    """
    egi = draw(_seed_egi())
    positive_areas = [a for a in egi.area.keys() if _is_positive_area(egi, a)]
    if not positive_areas:
        assume(False)
    area_id = draw(st.sampled_from(positive_areas))
    contents = list(_direct_area_contents(egi, area_id))
    if not contents:
        assume(False)
    selection = frozenset(
        draw(st.sets(st.sampled_from(contents), min_size=1))
    )

    # Match ERA's actual closure semantics (issue #9): for_erasure=True.
    validator = SubgraphClosureValidator(egi)
    analysis = validator.analyze_closure(
        selection, allow_expansion=True, context_area=area_id,
        for_erasure=True,
    )
    assume(analysis.is_closed)
    return egi, area_id, selection


def _restore_erased(
    g_after: RelationalGraphWithCuts,
    g_before: RelationalGraphWithCuts,
    erased: frozenset,
    target_area: ElementID,
) -> RelationalGraphWithCuts:
    """Re-add the erased closure to ``g_after`` using ``g_before`` as the
    source of truth for IDs, nu, rel, and area placement.

    This is the structural inverse of ERA's mutation, intentionally
    bypassing Dau's INS (whose polarity preconditions disallow re-insertion
    into a positive area). The point is to test that ERA's removal is
    bijective with the closure-set-difference.
    """
    new_V = set(g_after.V)
    new_E = set(g_after.E)
    new_Cut = set(g_after.Cut)
    new_nu = dict(g_after.nu)
    new_rel = dict(g_after.rel)
    new_area = {k: set(v) for k, v in g_after.area.items()}

    # Restore vertices / edges / cuts that were erased
    for v in g_before.V:
        if v.id in erased and not any(x.id == v.id for x in new_V):
            new_V.add(v)
    for e in g_before.E:
        if e.id in erased:
            if not any(x.id == e.id for x in new_E):
                new_E.add(e)
            new_nu[e.id] = g_before.nu[e.id]
            if e.id in g_before.rel:
                new_rel[e.id] = g_before.rel[e.id]
    for c in g_before.Cut:
        if c.id in erased and not any(x.id == c.id for x in new_Cut):
            new_Cut.add(c)

    # Restore area mapping for areas that existed before
    for area_id, contents in g_before.area.items():
        if area_id in erased:
            # Erased cut — restore its area entry verbatim
            new_area[area_id] = set(contents)
        else:
            # Preserved area — add back any erased elements that lived here
            restored_here = {e for e in contents if e in erased}
            new_area.setdefault(area_id, set()).update(restored_here)

    return RelationalGraphWithCuts(
        V=frozenset(new_V),
        E=frozenset(new_E),
        nu=frozendict(new_nu),
        sheet=g_after.sheet,
        Cut=frozenset(new_Cut),
        area=frozendict({k: frozenset(v) for k, v in new_area.items()}),
        rel=frozendict(new_rel),
    )


class TestErasureRestoreReversibility:
    """ERA's mutation is the structural inverse of re-adding the closure.

    This is a weaker claim than "ERA and INS are inverse rules" (they aren't,
    in Dau's calculus). It's a precise claim about ERA's bookkeeping:
    everything in the closure is removed, nothing else is, and re-inserting
    the same elements at the same positions reproduces the original EGI.
    """

    @settings(
        max_examples=120,
        deadline=None,
        suppress_health_check=[HealthCheck.too_slow, HealthCheck.filter_too_much],
    )
    @given(_era_target())
    def test_era_then_restore_is_structural_identity(self, params):
        egi, area_id, selection = params

        # Compute the closure expansion ERA will perform internally — this
        # is the exact set of element IDs ERA's mutation should remove.
        # Must mirror ERA's for_erasure=True (issue #9).
        validator = SubgraphClosureValidator(egi)
        analysis = validator.analyze_closure(
            selection, allow_expansion=True, context_area=area_id,
            for_erasure=True,
        )
        expected_erased = analysis.closed_subgraph

        polarity, depth = egi.area_polarity(area_id)
        ctx = TransformationContext(
            source_egi=egi,
            target_area=area_id,
            selected_subgraph=selection,
            area_polarity=polarity,
            nesting_depth=depth,
        )
        result = ErasureRule().apply_transformation(ctx)
        assert result.success, f"ERA failed: {result.error_message}"
        g_after = result.result_egi

        # ERA must have removed exactly the expanded closure.
        for v in g_after.V:
            assert v.id not in expected_erased, f"ERA left erased vertex {v.id}"
        for e in g_after.E:
            assert e.id not in expected_erased, f"ERA left erased edge {e.id}"
        for c in g_after.Cut:
            assert c.id not in expected_erased, f"ERA left erased cut {c.id}"

        # Restoring the erased closure to the same area must recover the original.
        g_restored = _restore_erased(g_after, egi, expected_erased, area_id)

        assert g_restored.sheet == egi.sheet
        assert g_restored.V == egi.V, (
            f"V mismatch after restore: original_minus_restored="
            f"{ {v.id for v in egi.V} - {v.id for v in g_restored.V} }"
        )
        assert g_restored.E == egi.E
        assert g_restored.Cut == egi.Cut
        assert g_restored.nu == egi.nu
        assert g_restored.rel == egi.rel
        assert dict(g_restored.area) == dict(egi.area), (
            f"area mismatch after restore:\n"
            f"  original={dict(egi.area)}\n  restored={dict(g_restored.area)}"
        )


